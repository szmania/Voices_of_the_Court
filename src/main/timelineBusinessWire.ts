/**
 * §9.3 P5.4 source request contract wiring.
 *
 * Each business source (conversation/letter_reply/incoming_letter/battle/bookmark)
 * is wired to TransitionJournalApi.beginTransition with the source-specific
 * requestKey + commitMode, then to resolveTimelineStrict + v2 store writes.
 *
 * v1 getOrCreateChild eventKey dedup is no longer used for NEW records; the
 * journal API creates TimelineNodeV2 entries with transitionAttemptId linkage.
 *
 * Two commit modes use shared guard helpers:
 *   - `post-bump-node-only`: compares target epoch/current token, only fills
 *     in node/parent. Used by letter_reply, incoming_letter, battle.
 *   - `atomic-advance`: compares observed epoch/node/current token and target
 *     pending token, then advances epoch + consumes pending + writes target
 *     node/graph parent in one shot. Used by conversation.
 *
 * Both helpers first do source-appropriate identity/request/delivery guard,
 * and accept the target node as already-applied (so terminal attempts with
 * CK3 == target become idempotent updates rather than new attempts).
 */
