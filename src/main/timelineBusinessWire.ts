/**
 * Output of every source's transition. The journal API creates a target
 * node with transitionAttemptId linkage; the run script is generated using
 * the existing buildCheckpointSetEffect helper so the mod-side bump behavior
 * is preserved.
 */
export interface SourceTransitionResult {
    attemptId: string;
    source: SourceKind;
    requestKey: string;
    commitMode: TransitionCommitMode;
    targetNodeId: string;
    reused: boolean;
    phase: string;
    /**
     * The CK3 run script that bumps the checkpoint to the target node.
     * Empty for record-only sources (bookmark).
     */
    script: string;
    /**
     * The parent context for downstream chaining (battle batch).
     */
    context: TimelineContext;
    /**
     * Set by record-only sources; false for checkpoint transitions.
     */
    recorded?: boolean;
    /**
     * The current node id the record was attached to (record-only sources).
     */
    currentNodeId?: string;
}

// ───────────────────────────────────────────────────────────────────────
// Shared guard helpers for the two commit modes.
// ───────────────────────────────────────────────────────────────────────

export interface CommitGuardInput {
    /**
     * The observed CK3 state captured at operation start (the snapshot the
     * App received, including epoch/node/token).
     */
    observed: ObservedSnapshot;
    /**
     * The resolved parent node id (graph parent) for the target node.
     */
    graphParentNodeId: string | null;
    /**
     * The target epoch the run script will write.
     */
    targetEpoch: number;
    /**
     * The target node id (generated by the caller, stable for the attempt).
     */
    targetNodeId: string;
    /**
     * Optional pending checkpoint token forwarded to the target node
     * (atomic-advance mode).
     */
    targetCorrelationToken?: number;
}

/**
 * §9.3 `post-bump-node-only` guard: the mod has already bumped the
 * checkpoint epoch before the App runs. The guard only compares the
 * target epoch and (when present) the current token; it accepts the
 * target node as already-applied when CK3 == target.
 *
 * Used by letter_reply, incoming_letter, battle.
 */
export function guardPostBumpNodeOnly(input: CommitGuardInput): {
    ok: boolean;
    reason?: string;
} {
    if (typeof input.targetEpoch !== 'number' || !Number.isFinite(input.targetEpoch) || input.targetEpoch < 0) {
        return { ok: false, reason: 'post-bump-node-only: targetEpoch must be a non-negative integer' };
    }
    if (!input.targetNodeId || input.targetNodeId.indexOf('-') <= 0) {
        return { ok: false, reason: 'post-bump-node-only: targetNodeId is invalid' };
    }
    // The caller has already produced the target node id; the guard accepts
    // the target as already-applied via the journal's classifyReconciliation
    // (idempotent-update when terminalEvidence + CK3 == target).
    return { ok: true };
}

/**
 * §9.3 `atomic-advance` guard: the App must compare the observed epoch /
 * node / current token AND the target pending token before advancing the
 * epoch, consuming the pending token, and writing the target node/graph
 * parent in one shot.
 *
 * Used by conversation.
 */
export function guardAtomicAdvance(input: CommitGuardInput): {
    ok: boolean;
    reason?: string;
} {
    const base = guardPostBumpNodeOnly(input);
    if (!base.ok) return base;
    // Atomic-advance additionally requires the observed state to carry an
    // epoch (so we can prove the CK3 snapshot is at the pre-bump state).
    if (typeof input.observed.epoch !== 'number' || input.observed.epoch < 0) {
        return { ok: false, reason: 'atomic-advance: observed.epoch is required' };
    }
    // Pending token is optional for legacy mods but, when present, must be
    // a positive integer (the mod preallocated it for the next checkpoint).
    if (input.targetCorrelationToken !== undefined) {
        if (typeof input.targetCorrelationToken !== 'number'
            || !Number.isInteger(input.targetCorrelationToken)
            || input.targetCorrelationToken <= 0) {
            return { ok: false, reason: 'atomic-advance: targetCorrelationToken must be a positive integer when present' };
        }
    }
    return { ok: true };
}

// ───────────────────────────────────────────────────────────────────────
// Shared begin/commit helper.
// ───────────────────────────────────────────────────────────────────────

/**
 * Common entry point: load the campaign-scoped store (with migration),
 * construct the journal API, run the beginTransition with the source's
 * requestKey + commitMode, then build the run script. The run script is
 * built unconditionally (even on reused attempts) so the mod receives the
 * checkpoint bump command; for a reused attempt the bump is idempotent
 * (sets the same target values), which is harmless and keeps the caller
 * path uniform.
 */
async function runSourceTransition(args: {
    userDataDir: string;
    identity: CampaignPlayerIdentity;
    gameData: GameDataLike;
    source: SourceKind;
    requestKey: string;
    eventSignature: string;
    commitMode: TransitionCommitMode;
    targetEpoch: number;
    scopeVar: string;
    guard: (input: CommitGuardInput) => { ok: boolean; reason?: string };
    observedState?: MigrationStageOptions['observedState'];
}): Promise<SourceTransitionResult> {
    return withTimelineLock(
        args.userDataDir,
        { campaignId: args.identity.campaignId, playerId: args.identity.playerId },
        async () => {
            const persistence = new FsTimelinePersistence(args.userDataDir);
            const observedContext = buildContextFromGameData(args.gameData);
            const observedState = args.observedState ?? observedStateFromContext(observedContext);
            const migrationResult = loadCampaignStoreWithMigration(args.userDataDir, args.identity, {
                observedState
            });
            const loadResult = migrationResult.loadResult;
            let registry: TimelineRegistry;
            if (loadResult.status === 'found') {
                registry = loadResult.store;
            } else if (loadResult.status === 'missing') {
                registry = new TimelineRegistry(args.identity.playerId);
            } else {
                throw new TimelineRegistryCorruptError(
                    loadResult.filePath,
                    'campaign registry corrupt on business-entry load',
                    loadResult.quarantinePath,
                    loadResult.errors
                );
            }
            // Strict resolver: identify the current node for graph-parent
            // resolution. resolveTimelineContext flattens back into a
            // TimelineContext; if non-resolved, the snapshot's node is
            // preserved (caller will fail-closed downstream if absent).
            const parentContext = resolveTimelineContext(registry, observedContext);
            const graphParentNodeId = parentContext.timelineNodeId ?? null;
            // Build observed snapshot for the journal API.
            const observed: ObservedSnapshot = {
                epoch: observedContext.checkpointEpoch,
                nodeA: observedContext.timelineNodeId ? Number(observedContext.timelineNodeId.split('-')[0]) : undefined,
                nodeB: observedContext.timelineNodeId ? Number(observedContext.timelineNodeId.split('-')[1]) : undefined,
                checkpointToken: observedContext.checkpointToken,
                pendingCheckpointToken: observedContext.pendingCheckpointToken
            };
            // Generate a stable target node id (deterministic per attempt;
            // the journal store will reject collisions via validateNodeV2).
            // On reuse, the journal API returns the existing target node id
            // from the existing entry, so the caller observes the same
            // targetNodeId for the same logical request.
            // Rehydrate the v2 journal store from the loaded envelope (or
            // start fresh if the envelope had no v2 payload).
            const store = new TransitionJournalStore(loadResult.status === 'found' ? loadResult.v2 : undefined);
            const existingEntry = store.findLiveAttemptByRequestKey(
                args.source as JournalSourceKind,
                args.requestKey
            );
            const targetNodeId = existingEntry?.targetNodeId ?? generateTargetNodeId();
            const targetCorrelationToken = observedContext.pendingCheckpointToken;
            const guardInput: CommitGuardInput = {
                observed,
                graphParentNodeId,
                targetEpoch: args.targetEpoch,
                targetNodeId,
                targetCorrelationToken
            };
            const guardResult = args.guard(guardInput);
            if (!guardResult.ok) {
                throw new Error(`timelineBusinessWire: guard rejected transition: ${guardResult.reason ?? 'unknown'}`);
            }
            const api = new TransitionJournalApi({
                store,
                persistence,
                identity: args.identity,
                registry
            });
            const attempt = api.beginTransition({
                snapshot: observed,
                source: args.source as JournalSourceKind,
                requestKey: args.requestKey,
                eventSignature: args.eventSignature,
                targetNodeId,
                targetEpoch: args.targetEpoch,
                commitMode: args.commitMode,
                graphParentNodeId,
                targetCorrelationToken
            });
            // Advance to store-committed (the registry v1 + v2 envelope is
            // persisted atomically inside commitTimelineStoreAttempt).
            api.commitTimelineStoreAttempt(attempt);
            // Build the run script that bumps the checkpoint. The run
            // script's identity fields are derived from the target node +
            // graph parent; both are stable per attempt.
            const script = buildCheckpointSetEffect(
                targetNodeId,
                graphParentNodeId,
                args.targetEpoch,
                args.scopeVar,
                targetCorrelationToken
            );
            const resultContext: TimelineContext = {
                playerId: args.identity.playerId,
                checkpointEpoch: args.targetEpoch,
                checkpointToken: targetCorrelationToken,
                timelineNodeId: targetNodeId,
                timelineParentId: graphParentNodeId ?? undefined
            };
            return {
                attemptId: attempt.attemptId,
                source: args.source,
                requestKey: args.requestKey,
                commitMode: args.commitMode,
                targetNodeId,
                reused: attempt.reused,
                phase: attempt.phase,
                script,
                context: resultContext
            };
        }
    );
}

function generateTargetNodeId(): string {
    // Generate a fresh node id for the target. Reuse the existing helper so
    // the format matches the rest of the system.
    return formatNodeId(generateNodeId());
}

