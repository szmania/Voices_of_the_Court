// ───────────────────────────────────────────────────────────────────────
// Battle source: post-bump-node-only + slot+battleDeliveryId.
// Multiple battles per batch chain off the previous battle's context.
// ───────────────────────────────────────────────────────────────────────

export interface BattleBatchTransitionEntry {
    /**
     * The battle facts signature (slot|playerId|date|location|...). Stored
     * as eventSignature on the v2 node; NOT used as requestKey.
     */
    eventSignature: string;
    slotId: string;
    /**
     * Mod-provided battle delivery id (occurrence evidence). Combined with
     * slotId to form the requestKey.
     */
    battleDeliveryId: string;
    context: TimelineContext;
    nextEpoch: number | undefined;
}

export interface BattleBatchTransitionInput {
    userDataDir: string;
    gameData: GameDataLike;
    identity: CampaignPlayerIdentity;
    entries: BattleBatchTransitionEntry[];
}

export interface BattleBatchTransitionResult {
    timelines: Map<string, SourceTransitionResult>;
}

export function battleRequestKey(slotId: string, battleDeliveryId: string): string {
    return `${slotId}|${battleDeliveryId}`;
}

export async function runBattleTimelineBatchTransition(
    input: BattleBatchTransitionInput
): Promise<BattleBatchTransitionResult> {
    return withTimelineLock(
        input.userDataDir,
        { campaignId: input.identity.campaignId, playerId: input.identity.playerId },
        async () => {
            const persistence = new FsTimelinePersistence(input.userDataDir);
            const firstContext = input.entries[0]?.context ?? { playerId: input.identity.playerId };
            const observedState = observedStateFromContext(firstContext);
            const migrationResult = loadCampaignStoreWithMigration(input.userDataDir, input.identity, {
                observedState
            });
            const loadResult = migrationResult.loadResult;
            let registry: TimelineRegistry;
            if (loadResult.status === 'found') {
                registry = loadResult.store;
            } else if (loadResult.status === 'missing') {
                registry = new TimelineRegistry(input.identity.playerId);
            } else {
                throw new TimelineRegistryCorruptError(
                    loadResult.filePath,
                    'campaign registry corrupt on battle-report load',
                    loadResult.quarantinePath,
                    loadResult.errors
                );
            }
            const store = new TransitionJournalStore(loadResult.status === 'found' ? loadResult.v2 : undefined);
            const api = new TransitionJournalApi({
                store,
                persistence,
                identity: input.identity,
                registry
            });
            const timelines = new Map<string, SourceTransitionResult>();
            let chainedContext: TimelineContext | undefined;
            let previousSnapshotKey: string | undefined;
            for (const entry of input.entries) {
                const snapshotContext = resolveTimelineContext(registry, entry.context);
                const snapshotKey = [
                    snapshotContext.timelineNodeId ?? '',
                    snapshotContext.checkpointEpoch ?? '',
                    snapshotContext.checkpointToken ?? '',
                    snapshotContext.pendingCheckpointToken ?? ''
                ].join('\u001f');
                const parentContext = previousSnapshotKey === snapshotKey && chainedContext
                    ? chainedContext
                    : snapshotContext;
                const nextEpoch = previousSnapshotKey === snapshotKey
                    && parentContext.checkpointEpoch !== undefined
                    ? Math.max(entry.nextEpoch ?? parentContext.checkpointEpoch + 1, parentContext.checkpointEpoch + 1)
                    : entry.nextEpoch;
                const graphParentNodeId = parentContext.timelineNodeId ?? null;
                const observed: ObservedSnapshot = {
                    epoch: parentContext.checkpointEpoch,
                    nodeA: parentContext.timelineNodeId ? Number(parentContext.timelineNodeId.split('-')[0]) : undefined,
                    nodeB: parentContext.timelineNodeId ? Number(parentContext.timelineNodeId.split('-')[1]) : undefined,
                    checkpointToken: parentContext.checkpointToken,
                    pendingCheckpointToken: parentContext.pendingCheckpointToken
                };
                const requestKey = battleRequestKey(entry.slotId, entry.battleDeliveryId);
                const targetNodeId = (() => {
                    const existingBattle = store.findLiveAttemptByRequestKey(
                        'battle',
                        requestKey
                    );
                    return existingBattle?.targetNodeId ?? generateTargetNodeId();
                })();
                const targetCorrelationToken = parentContext.pendingCheckpointToken;
                const resolvedNextEpoch = nextEpoch ?? (parentContext.checkpointEpoch !== undefined ? parentContext.checkpointEpoch + 1 : 0);
                const guardInput: CommitGuardInput = {
                    observed,
                    graphParentNodeId,
                    targetEpoch: resolvedNextEpoch,
                    targetNodeId,
                    targetCorrelationToken
                };
                const guardResult = guardPostBumpNodeOnly(guardInput);
                if (!guardResult.ok) {
                    throw new Error(`timelineBusinessWire.battle: guard rejected transition: ${guardResult.reason ?? 'unknown'}`);
                }
                const attempt = api.beginTransition({
                    snapshot: observed,
                    source: 'battle',
                    requestKey,
                    eventSignature: entry.eventSignature,
                    targetNodeId,
                    targetEpoch: resolvedNextEpoch,
                    commitMode: 'post-bump-node-only',
                    graphParentNodeId,
                    targetCorrelationToken
                });
                api.commitTimelineStoreAttempt(attempt);
                const script = buildCheckpointSetEffect(
                    targetNodeId,
                    graphParentNodeId,
                    resolvedNextEpoch,
                    'votc_battle_report_player',
                    targetCorrelationToken
                );
                const resultContext: TimelineContext = {
                    playerId: input.identity.playerId,
                    checkpointEpoch: resolvedNextEpoch,
                    checkpointToken: targetCorrelationToken,
                    timelineNodeId: targetNodeId,
                    timelineParentId: graphParentNodeId ?? undefined
                };
                timelines.set(entry.eventSignature, {
                    attemptId: attempt.attemptId,
                    source: 'battle',
                    requestKey,
                    commitMode: 'post-bump-node-only',
                    targetNodeId,
                    reused: attempt.reused,
                    phase: attempt.phase,
                    script,
                    context: resultContext
                });
                previousSnapshotKey = snapshotKey;
                chainedContext = resultContext;
            }
            return { timelines };
        }
    );
}

// ───────────────────────────────────────────────────────────────────────
// Bookmark source: record-only (no checkpoint transition).
// ───────────────────────────────────────────────────────────────────────

export interface BookmarkImportInput {
    userDataDir: string;
    gameData: GameDataLike;
    identity: CampaignPlayerIdentity;
    /**
     * Idempotent import id (caller-generated). Re-importing with the same
     * id is a no-op.
     */
    importId: string;
}

export interface BookmarkImportResult {
    /**
     * Current node id resolved by strict resolver.
     */
    currentNodeId: string | undefined;
    /**
     * True if this call wrote a new record; false if the import id was
     * already present (idempotent).
     */
    recorded: boolean;
}

/**
 * Record-only: bookmark imports do NOT create a checkpoint transition.
 * Instead, they attach an idempotent import record to the current node
 * resolved by resolveTimelineStrict.
 *
 * The current implementation stores the import id on the v2 node's
 * `eventSignature` field (prefixed with `bookmark:`) so a re-import with
 * the same import id is detected and skipped. Phase 8 will replace this
 * with the summary-override machinery.
 */
export async function recordBookmarkImport(
    input: BookmarkImportInput
): Promise<BookmarkImportResult> {
    return withTimelineLock(
        input.userDataDir,
        { campaignId: input.identity.campaignId, playerId: input.identity.playerId },
        async () => {
            const persistence = new FsTimelinePersistence(input.userDataDir);
            const observedContext = buildContextFromGameData(input.gameData);
            const observedState = observedStateFromContext(observedContext);
            const migrationResult = loadCampaignStoreWithMigration(input.userDataDir, input.identity, {
                observedState
            });
            const loadResult = migrationResult.loadResult;
            let registry: TimelineRegistry;
            if (loadResult.status === 'found') {
                registry = loadResult.store;
            } else if (loadResult.status === 'missing') {
                registry = new TimelineRegistry(input.identity.playerId);
            } else {
                throw new TimelineRegistryCorruptError(
                    loadResult.filePath,
                    'campaign registry corrupt on bookmark-import load',
                    loadResult.quarantinePath,
                    loadResult.errors
                );
            }
            // Use the strict resolver to identify the current node.
            const resolution = resolveTimelineStrict({ registry, context: observedContext });
            const currentNodeId = resolution.status === 'resolved' ? resolution.context.timelineNodeId : observedContext.timelineNodeId;
            if (!currentNodeId) {
                // No current node: cannot attach the import record. Return
                // a non-recorded result so the caller knows the import was
                // a no-op (Phase 8 will introduce summary-override nodes
                // that do not require a current node).
                return { currentNodeId: undefined, recorded: false };
            }
            const store = new TransitionJournalStore(loadResult.status === 'found' ? loadResult.v2 : undefined);
            // Idempotency: scan the v2 nodes for an existing import record
            // with this import id. We store the import id on the node's
            // eventSignature (prefixed) so we can detect duplicates without
            // a separate index.
            const importSignature = `bookmark:${input.importId}`;
            const existing = store.getAllNodes().find(n => n.eventSignature === importSignature);
            if (existing) {
                // Idempotent: the same import id has already been recorded.
                persistence.saveStoreWithIdentity(input.identity, registry, store.serialize());
                return { currentNodeId, recorded: false };
            }
            // Record-only: we do NOT create a transition attempt. We
            // attach the import record to the current node by adding a
            // dedicated v2 node whose parent is the current node. The v2
            // node schema requires a non-empty transitionAttemptId, so we
            // use the `bookmark:<importId>` sentinel to mark record-only
            // nodes (no journal entry is created for this id). The import
            // id is also stored as eventSignature so future imports can
            // detect duplicates.
            const importNodeId = generateTargetNodeId();
            const now = new Date().toISOString();
            store.upsertNode(importNodeId, {
                parentId: currentNodeId,
                epoch: observedContext.checkpointEpoch ?? 0,
                source: 'summary_manual',
                transitionAttemptId: `bookmark:${input.importId}`,
                requestKey: input.importId,
                eventSignature: importSignature,
                createdAt: now
            });
            persistence.saveStoreWithIdentity(input.identity, registry, store.serialize());
            return { currentNodeId, recorded: true };
        }
    );
}

